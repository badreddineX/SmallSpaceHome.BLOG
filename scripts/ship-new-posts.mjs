// ship-new-posts.mjs — run after adding new blog posts, around `git push`:
//
//   npm run ship            normal run
//   npm run ship -- --dry   show what would happen, write nothing, submit nothing
//
// Three steps, none of which block anything (a failure here never stops a deploy):
//
//   1. INDEX   Rebuild the IndexNow URL list from src/content/blog/ + core pages,
//              rewrite indexnow-submit.js, and POST the list to the IndexNow API.
//   2. CSV     Append any post that is missing from the performance tracker
//              docs/CAD-blog-categories-articles.csv (matched by /blog/<slug>).
//   3. NEWS    Warn if a new post's frontmatter datePublished is >7 days old or
//              in the future — the weekly newsletter digest (api/broadcast.js)
//              filters posts by that date and will silently skip anything the
//              cron considers "already covered".
//
// See SHIP-PIPELINE.md at the "space work (blogging)" folder root for the why.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

// ---------------------------------------------------------------- config (CAD)
const HOST = 'smallspacehome.ca';
const KEY = '73336c6e688841b4bb0d5d674fa0ebda';
const SITE = 'https://smallspacehome.ca';
const TRAIL = ''; // astro trailingSlash: 'never'
const CSV_REL = 'docs/CAD-blog-categories-articles.csv';
const CORE_PATHS = [
  '/', '/about', '/author', '/contact', '/editorial-policy',
  '/free-storage-checklist', '/privacy-policy', '/terms', '/blog',
];
// ---------------------------------------------------------------------------

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BLOG_DIR = join(ROOT, 'src/content/blog');
const CSV_PATH = join(ROOT, CSV_REL);
const INDEXNOW_PATH = join(ROOT, 'indexnow-submit.js');
const DRY = process.argv.includes('--dry') || process.argv.includes('--dry-run');
const today = new Date().toISOString().slice(0, 10);

const log = (...a) => console.log(...a);
const warn = (...a) => console.log('  \x1b[33m!\x1b[0m', ...a);

function fm(body, field) {
  const m = body.match(new RegExp(`^${field}:\\s*"?([^"\\n]+?)"?\\s*$`, 'm'));
  return m ? m[1].trim() : '';
}

function gitFirstDate(file) {
  try {
    const out = execFileSync('git', ['log', '--diff-filter=A', '--format=%as', '--', file], {
      cwd: ROOT, encoding: 'utf8',
    }).trim().split('\n').filter(Boolean);
    return out.length ? out[out.length - 1] : '';
  } catch {
    return '';
  }
}

// --- collect posts -----------------------------------------------------------
const files = readdirSync(BLOG_DIR).filter((f) => f.endsWith('.md') || f.endsWith('.mdx'));
const posts = files.map((f) => {
  const body = readFileSync(join(BLOG_DIR, f), 'utf8');
  const slug = f.replace(/\.mdx?$/, '');
  return {
    slug,
    file: join(BLOG_DIR, f),
    relFile: `src/content/blog/${f}`,
    url: `${SITE}/blog/${slug}${TRAIL}`,
    title: fm(body, 'title'),
    category: fm(body, 'category'),
    datePublished: fm(body, 'datePublished'),
    draft: /^draft:\s*true\s*$/m.test(body),
  };
}).filter((p) => !p.draft);

log(`\n${posts.length} published posts found.\n`);

// --- 1. INDEX --------------------------------------------------------------
const urlList = [
  ...CORE_PATHS.map((p) => `${SITE}${p === '/' ? '/' : p + TRAIL}`),
  ...posts.map((p) => p.url).sort(),
];
const indexnowFile =
`const host = "${HOST}";
const key = "${KEY}";
const keyLocation = \`https://\${host}/\${key}.txt\`;

// urlList is regenerated by scripts/ship-new-posts.mjs — do not hand-edit.
const urlList = [
${urlList.map((u) => `  ${JSON.stringify(u)},`).join('\n')}
];

async function main() {
  const res = await fetch("https://api.indexnow.org/indexnow", {
    method: "POST",
    headers: { "Content-Type": "application/json; charset=utf-8" },
    body: JSON.stringify({ host, key, keyLocation, urlList }),
  });
  console.log("Status:", res.status);
  console.log(await res.text());
}

main();
`;

log('1. INDEX');
if (DRY) {
  log(`   would write indexnow-submit.js with ${urlList.length} URLs`);
  log(`   would POST ${urlList.length} URLs to api.indexnow.org`);
} else {
  writeFileSync(INDEXNOW_PATH, indexnowFile);
  log(`   indexnow-submit.js rewritten (${urlList.length} URLs)`);
  try {
    const res = await fetch('https://api.indexnow.org/indexnow', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json; charset=utf-8' },
      body: JSON.stringify({
        host: HOST, key: KEY,
        keyLocation: `https://${HOST}/${KEY}.txt`,
        urlList,
      }),
    });
    log(`   IndexNow POST → HTTP ${res.status}`);
  } catch (e) {
    warn(`IndexNow POST failed (non-fatal): ${e.message}`);
  }
}

// --- 2. CSV --------------------------------------------------------------
log('\n2. CSV');
let csv = '';
try { csv = readFileSync(CSV_PATH, 'utf8'); } catch { warn(`${CSV_REL} not found — skipping`); }
const missing = csv ? posts.filter((p) => !csv.includes(`/blog/${p.slug}`)) : [];
if (!csv) {
  // handled above
} else if (!missing.length) {
  log('   tracker already lists every post — nothing to add');
} else {
  const q = (s) => `"${String(s).replace(/"/g, '""')}"`;
  const rows = missing.map((p) => {
    const realDate = gitFirstDate(p.relFile) || today;
    // Category,Title,URL,Real_Git_Date,Frontmatter_Date,Impr28,Clk28,Pos,Bucket,Action,Impr90,Clk90,Note
    return [
      p.category || 'Uncategorised',
      q(p.title || p.slug),
      p.url,
      realDate,
      p.datePublished || '',
      '', '', '', '',
      q(`NEW — shipped ${today}, awaiting indexation`),
      '', '', '',
    ].join(',');
  });
  if (DRY) {
    log(`   would append ${rows.length} row(s):`);
    missing.forEach((p) => log(`     + ${p.slug}  [${p.category || '?'}]`));
  } else {
    const sep = csv.endsWith('\n') ? '' : '\n';
    writeFileSync(CSV_PATH, csv + sep + rows.join('\n') + '\n');
    log(`   appended ${rows.length} row(s):`);
    missing.forEach((p) => log(`     + ${p.slug}`));
  }
}

// --- 3. NEWS --------------------------------------------------------------
log('\n3. NEWSLETTER (frontmatter date sanity for the weekly digest)');
const weekAgo = new Date(Date.now() - 7 * 864e5).toISOString().slice(0, 10);
const checkList = missing.length ? missing : posts.filter((p) => (gitFirstDate(p.relFile) || today) >= weekAgo);
if (!checkList.length) {
  log('   no recently-added posts to check');
} else {
  for (const p of checkList) {
    const d = p.datePublished;
    if (!d) { warn(`${p.slug}: no datePublished — digest cannot place it`); continue; }
    if (d > today) warn(`${p.slug}: datePublished ${d} is in the FUTURE — digest won't send it until then`);
    else if (d < weekAgo) warn(`${p.slug}: datePublished ${d} is >7 days old — the Monday digest may treat it as already covered and skip it. Set it to ${today} if you want it emailed.`);
    else log(`   ${p.slug}: datePublished ${d} — OK`);
  }
}

log(`\n${DRY ? '[dry run — nothing written]' : 'Done.'}  Manual follow-ups: Pinterest pins, hub↔post internal links, mention new post in next backlink outreach.\n`);
